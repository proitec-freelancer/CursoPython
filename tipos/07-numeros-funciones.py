import math

print(round(1.3))  # Nos muestra al número que se encuentra mas cercano
print(round(1.7))
print(round(1.5))
print(abs(-77))  # Nos muestra el valor absoluto y saca los signos
print(abs(55))  # Nos muestra el valor absoluto y saca los signos

print(math.ceil(1.1))  # Nos dirige al número entero mas cercano hacia arriba
print(math.floor(1.9999))  # Nos dirige al número entero mas cercano hacia abajo
# print(math.isnan(23)) # Nos muestra si el valor es NaN (Not a Number)
print(math.pow(10, 3))  # Nos muestra el valor de la potencia
print(math.sqrt(9))  # Nos muestra la raíz cuadrada
